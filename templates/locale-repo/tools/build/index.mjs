#!/usr/bin/env node
/**
 * `npm run build` with a production-sized heap.
 *
 * The static renderer is the peak; without this wrapper a big pass can die with
 * "FATAL ERROR: Reached heap limit" after half the output is already written.
 * The heap is set here, not in `.env`, so a plain `npm run build` works in any
 * shell (CI included).
 *
 * ## Monolingual mode
 *
 * This repository builds **English only**. When `SITE_LOCALE` is set (for
 * example `SITE_LOCALE=en npm run build`) the Docusaurus step runs
 *
 *   docusaurus build --locale <SITE_LOCALE> --out-dir build
 *
 * `--out-dir` is passed explicitly on purpose: it is the directory Docusaurus
 * wipes before rendering, and spelling it out keeps that destructive default
 * visible next to the locale flag. Every later step (pagefind, llms.txt) then
 * walks the same `build/`, which holds one locale, so nothing downstream has to
 * know about the other one.
 *
 * Without `SITE_LOCALE` the wrapper keeps the old behaviour: Docusaurus builds
 * every declared locale into `build/`. That mode is only useful for a
 * same-repo bilingual site, which this repository is not.
 *
 * Extra arguments go to `docusaurus build`:
 *   node tools/build/index.mjs --locale en
 *
 * ## Asset-host fail-closed gate (issue 5)
 *
 * When `locales.json` declares more than one locale and this checkout is the
 * resource host (the default `en` locale is built here, or a non-default locale
 * names this checkout as its repo), `ASSET_HOST` must be `true`. Otherwise this
 * entry exits 1 immediately: without it `tools/build/slim.mjs` prunes
 * `build/img` down to the files this site references, while localized pages
 * load their Markdown images from `/img/<hash>` on this host — the result was
 * 1510 of 1702 referenced blobs 404ing. A monolingual registry, a locale repo
 * that is not the host, or a registry without `locales.json` keeps the old
 * behaviour. `slim.mjs` repeats the same gate so a direct `npm run build:slim`
 * cannot bypass it.
 *
 * `--asset-host-check` runs only this gate (no Docusaurus, no LLM) and prints a
 * JSON decision; it is used by the offline drill.
 */

import {spawnSync} from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const HEAP_MB = Number(process.env.BUILD_HEAP_MB || 4096);
const current = process.env.NODE_OPTIONS || '';
const nodeOptions = /--max-old-space-size=/.test(current)
  ? current
  : `${current} --max-old-space-size=${HEAP_MB}`.trim();
console.log('[build] NODE_OPTIONS =', nodeOptions);

/**
 * Source-data fail-closed gate: `hardware/`, `blog/` and `changelog/` are
 * committed Markdown source data in HEAD (like versions.json / sidebars.ts),
 * never generated by the pipeline. A clean-room setup that wipes "generated"
 * paths must retain them; without this guard the build silently ships a site
 * with no hardware pages, blog posts or changelog entries. Fail before rendering.
 *
 * `static/img/` and `static/assets/` are deliberately NOT gated here. In a
 * locale repository every asset is served from the shared `ASSET_ORIGIN` (the
 * English hub): `docusaurus.config.ts` sets `staticDirectories: []` in that
 * mode and `.github/workflows/pages.yml` asserts `static/` does not exist at
 * all. A local `static/` floor would contradict that contract and can never be
 * satisfied by a locale checkout that receives published content.
 */
const REQUIRED_BUILD_INPUTS = [
  {dir: 'hardware', minMd: 250},
  {dir: 'blog', minMd: 6},
  {dir: 'changelog', minMd: 100},
];

function assertBuildInputs() {
  const problems = [];
  const counts = [];
  for (const {dir, minMd} of REQUIRED_BUILD_INPUTS) {
    const abs = path.join(REPO, dir);
    if (!fs.existsSync(abs) || !fs.statSync(abs).isDirectory()) {
      counts.push(`${dir}=MISSING (min ${minMd} md)`);
      problems.push(`${dir}/ is missing`);
      continue;
    }
    let count = 0;
    const walk = (d) => {
      for (const entry of fs.readdirSync(d, {withFileTypes: true})) {
        const full = path.join(d, entry.name);
        if (entry.isDirectory()) walk(full);
        else if (entry.name.endsWith('.md')) count++;
      }
    };
    walk(abs);
    counts.push(`${dir}=${count} md (min ${minMd})`);
    if (count < minMd) {
      problems.push(`${dir}/ has only ${count} .md files (need >= ${minMd})`);
    }
  }
  if (problems.length) {
    console.error(
      `[build] FATAL required source data missing/incomplete: ${problems.join('; ')}. ` +
        'retain these as source data; clean-room setup must not delete them ' +
        '(they are committed in HEAD, never generated by the pipeline; ' +
        'restore with `git checkout -- hardware blog changelog`).',
    );
    process.exit(1);
  }
  console.log(`[build] source-data gate ok: ${counts.join(', ')}`);
}

assertBuildInputs();

/**
 * `ASSET_ORIGIN`（共享资源源站，带路径前缀，不带尾斜杠）。
 *
 * 设置时 `docusaurus.config.ts` 把 `staticDirectories` 设成空数组，站内资源
 * 引用改写到该源站，`static/` 不再参与构建。这里只负责把模式说清楚，并在
 * 发现遗留 `static/` 内容时警告：它会被**忽略**，不是被合并。旧构建可能在
 * `static/` 里留下 `cli/` 与 `cli-compare.json`（现在 `ASSET_ORIGIN` 模式把
 * 它们写进 `work/cli/`），这两个不算遗留内容。
 */
const assetOrigin = (process.env.ASSET_ORIGIN || '').trim().replace(/\/+$/, '');
const STATIC_DIR = path.join(REPO, 'static');
const GENERATED_STATIC_ENTRIES = new Set(['cli', 'cli-compare.json']);

function warnAboutIgnoredStatic() {
  if (!fs.existsSync(STATIC_DIR) || !fs.statSync(STATIC_DIR).isDirectory()) return;
  const leftovers = fs
    .readdirSync(STATIC_DIR)
    .filter((entry) => !GENERATED_STATIC_ENTRIES.has(entry));
  if (leftovers.length === 0) return;
  console.warn(
    `[build] WARN ASSET_ORIGIN is set: static/ is ignored by this build ` +
      `(staticDirectories = []). Leftover entries: ${leftovers.join(', ')}. ` +
      'Remove static/ — localized repositories serve assets from the shared origin.',
  );
}

if (assetOrigin) {
  console.log(`[build] shared asset origin: ${assetOrigin} (static/ is not published)`);
  warnAboutIgnoredStatic();
} else if (!fs.existsSync(STATIC_DIR) || !fs.statSync(STATIC_DIR).isDirectory()) {
  console.warn(
    '[build] WARN static/ is missing and ASSET_ORIGIN is unset: root-absolute ' +
      'asset references (/img/…, /assets/…, /videos/…) will 404. Set ASSET_ORIGIN ' +
      'to the asset host (see guides/CI.md) or restore static/.',
  );
}

/**
 * Read `locales.json` without throwing: an absent/unreadable registry means
 * "multi-locale mode is not configured", so the gate stays out of the way.
 */
function readLocaleRegistry() {
  try {
    const parsed = JSON.parse(fs.readFileSync(path.join(REPO, 'locales.json'), 'utf8'));
    if (!parsed || typeof parsed.locales !== 'object' || parsed.locales === null) return null;
    return {
      default: String(parsed.default || 'en'),
      locales: Object.entries(parsed.locales),
    };
  } catch {
    return null;
  }
}

/** `owner/name` -> `name`, used to match a registry entry to this checkout. */
function repoNameOf(entry) {
  return String((entry && entry.repo) || '')
    .trim()
    .replace(/\/+$/, '')
    .split('/')
    .pop() || '';
}

/**
 * Decide whether this checkout is the shared asset host.
 *
 * Only a multi-locale registry can create the gap: a single-locale repo keeps
 * every blob it publishes and has nobody else referencing it. The host is the
 * checkout that builds the default locale (`en` by registry contract), plus a
 * checkout another non-default locale explicitly points at via its `repo`
 * field. `SITE_LOCALE` identifies the checkout first; without it the repo
 * directory name is matched against the registry's `repo` values.
 */
function assetHostRequirement() {
  const registry = readLocaleRegistry();
  if (!registry) return {required: false, reason: 'locales.json missing or unreadable'};
  if (registry.locales.length < 2) {
    return {required: false, reason: 'single-locale registry'};
  }
  const siteLocale = (process.env.SITE_LOCALE || '').trim();
  const repoName = path.basename(REPO);
  let ownLocale = null;
  if (siteLocale && registry.locales.some(([code]) => code === siteLocale)) {
    ownLocale = siteLocale;
  } else {
    const match = registry.locales.find(([, entry]) => repoNameOf(entry) === repoName);
    if (match) ownLocale = match[0];
  }
  const isEnglishHub =
    !!ownLocale && ownLocale === registry.default && registry.default === 'en';
  // A non-default locale that names this checkout (and is not this checkout's
  // own locale) means this checkout serves assets for another locale too.
  const hostedLocales = registry.locales
    .filter(
      ([code, entry]) =>
        code !== registry.default && code !== ownLocale && repoNameOf(entry) === repoName,
    )
    .map(([code]) => code);
  const required = isEnglishHub || hostedLocales.length > 0;
  const reasons = [];
  if (isEnglishHub) reasons.push(`this checkout builds default locale ${registry.default}`);
  if (hostedLocales.length) {
    reasons.push(`non-default locale(s) ${hostedLocales.join(', ')} point at this checkout`);
  }
  return {
    required,
    reason: reasons.join('; ') ||
      (ownLocale ? `checkout locale ${ownLocale} is not the asset host` : 'checkout locale not identified'),
    ownLocale,
    defaultLocale: registry.default,
    localeCount: registry.locales.length,
    hostedLocales,
  };
}

const extraArgs = process.argv.slice(2);
const assetHostCheckOnly = extraArgs.some(
  (arg) => arg === '--asset-host-check' || arg === '--check-asset-host',
);
const assetHost = /^(?:1|true|yes)$/i.test((process.env.ASSET_HOST || '').trim());
const hostRequirement = assetHostRequirement();

if (assetHostCheckOnly) {
  const ok = !hostRequirement.required || assetHost;
  console.log(
    JSON.stringify(
      {
        assetHost,
        required: hostRequirement.required,
        reason: hostRequirement.reason,
        ownLocale: hostRequirement.ownLocale,
        defaultLocale: hostRequirement.defaultLocale,
        localeCount: hostRequirement.localeCount,
        hostedLocales: hostRequirement.hostedLocales,
        ok,
      },
      null,
      2,
    ),
  );
  process.exit(ok ? 0 : 1);
}
if (hostRequirement.required && !assetHost) {
  console.error(
    `[build] FATAL this checkout is the asset host (${hostRequirement.reason}; ` +
      `${hostRequirement.localeCount} locales declared) but ASSET_HOST is not true. ` +
      'slim would prune build/img and every localized Markdown image would 404. ' +
      'Set ASSET_HOST=true (as .github/workflows/pages.yml already does) before building.',
  );
  process.exit(1);
}
if (hostRequirement.required) {
  console.log('[build] ASSET_HOST=true: slim will keep the full build/img tree');
}
const hasLocaleArg = extraArgs.some(
  (arg) => arg === '--locale' || arg.startsWith('--locale='),
);
// `SITE_LOCALE` is also read by `tools/build/llms.mjs`; an explicit `--locale`
// on the command line wins so the two steps can never disagree.
const siteLocale = (process.env.SITE_LOCALE || '').trim();
const singleLocale = siteLocale && !hasLocaleArg ? siteLocale : null;

if (singleLocale) {
  console.log(`[build] single-locale mode: --locale ${singleLocale} --out-dir build`);
} else if (!siteLocale) {
  console.log('[build] no SITE_LOCALE: Docusaurus builds every declared locale');
}

const buildArgs = [
  'docusaurus',
  'build',
  '--out-dir',
  'build',
  ...(singleLocale ? ['--locale', singleLocale] : []),
  ...extraArgs,
];

const steps = [
  ['npm', ['run', 'cli:build']],
  ['npx', buildArgs],
  // pagefind indexes whatever is in `build/`: in single-locale mode that is the
  // English tree only, so the search index has no Chinese entries either.
  ['npx', ['pagefind', '--site', 'build']],
  // llms.txt 用官方结构重写（分类 + 绝对 URL + 英文标题），每个版本目录一份。
  // 插件仍会先生成一份，这里在 build 末尾覆盖成官方结构。
  ['node', ['tools/build/llms.mjs']],
];

for (const [command, args] of steps) {
  const result = spawnSync(command, args, {
    cwd: REPO,
    stdio: 'inherit',
    env: {...process.env, NODE_OPTIONS: nodeOptions},
  });
  if (result.status !== 0) process.exit(result.status ?? 1);
}

/**
 * `ASSET_ORIGIN` 模式下 `cli:build` 把数据写进 `work/cli/`（本产物不发布
 * `static/`）。但 `cli-compare.json` 是 `src/components/CliCompare` 用
 * `fetch()` 读的：跨域请求需要 CORS，而英文站（GitHub Pages）不返回
 * `Access-Control-Allow-Origin`，所以它在任何模式下都必须留在本站。这里把它
 * 放到产物根，与 pagefind 索引同级。
 */
if (assetOrigin) {
  const source = path.join(REPO, 'work', 'cli', 'cli-compare.json');
  const target = path.join(REPO, 'build', 'cli-compare.json');
  if (fs.existsSync(source)) {
    fs.copyFileSync(source, target);
    console.log(
      `[build] published ${path.relative(REPO, target)} from work/cli ` +
        '(local: the asset host sends no CORS headers)',
    );
  } else {
    console.warn(
      '[build] WARN work/cli/cli-compare.json is missing: the CLI compare page will not load',
    );
  }
}
